import { useMemo, useState } from "react";
import type { Filters } from "./api";
import CapacityChart from "./components/CapacityChart";
import DataQualityPanel from "./components/DataQualityPanel";
import ForecastChart from "./components/ForecastChart";
import InventoryTable from "./components/InventoryTable";
import KpiCards from "./components/KpiCards";
import { useFetch } from "./useFetch";

export default function App() {
  const { state, retry } = useFetch<Filters>("/api/filters");
  const [plantId, setPlantId] = useState("");
  const [skuId, setSkuId] = useState("");

  const filters = state.status === "success" ? state.data : null;
  const skuOptions = useMemo(() => {
    if (!filters) return [];
    const seen = new Map<string, string>();
    filters.skus.filter((s) => !plantId || s.plant_id === plantId).forEach((s) => seen.set(s.sku_id, s.sku_name));
    return [...seen.entries()];
  }, [filters, plantId]);

  return (
    <div className="page">
      <header className="top">
        <div>
          <h1>Aapurti</h1>
          <p className="muted">Supply-chain analytics: forecasting, inventory visibility, capacity planning</p>
        </div>
        <a className="button" href="/export.xlsx" download>
          Download Excel
        </a>
      </header>
      <p className="banner" role="note">
        All data shown is <strong>synthetic</strong>, generated by a seeded script. It is not real company data.
      </p>

      <div className="filters">
        {state.status === "error" ? (
          <div className="state error inline-error" role="alert">
            Could not load filters: {state.error}{" "}
            <button type="button" onClick={retry}>
              Retry
            </button>
          </div>
        ) : (
          <>
            <label>
              Plant
              <select
                value={plantId}
                disabled={!filters}
                onChange={(e) => {
                  setPlantId(e.target.value);
                  setSkuId("");
                }}
              >
                <option value="">All plants</option>
                {filters?.plants.map((p) => (
                  <option key={p.plant_id} value={p.plant_id}>
                    {p.plant_id} {p.plant_name}
                  </option>
                ))}
              </select>
            </label>
            <label>
              SKU
              <select value={skuId} disabled={!filters} onChange={(e) => setSkuId(e.target.value)}>
                <option value="">All SKUs</option>
                {skuOptions.map(([id, name]) => (
                  <option key={id} value={id}>
                    {id} · {name}
                  </option>
                ))}
              </select>
            </label>
          </>
        )}
      </div>

      <KpiCards />
      <div className="grid">
        <div className="span2">
          <ForecastChart skuId={skuId} plantId={plantId} />
        </div>
        <InventoryTable plantId={plantId} />
        <CapacityChart plantId={plantId} />
        <div className="span2">
          <DataQualityPanel />
        </div>
      </div>
      <footer className="muted small">
        Spark runs in the batch step; this app serves pre-computed gold tables from SQLite. Synthetic data only.
      </footer>
    </div>
  );
}
